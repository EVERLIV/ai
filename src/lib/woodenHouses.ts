export const WOODEN_BUILDING_TYPE_LABELS = [
  ...new Set(WOODEN_HOUSE_CONFIGS.map((c) => c.buildingType)),
];

const WOODEN_LABEL_SET = new Set(WOODEN_BUILDING_TYPE_LABELS);

/** Тип дома для домов/коттеджей: кирпич/монолит + деревянные технологии. */
export function houseBuildingTypeOptions(
  base: readonly string[] = [],
): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const v of [...base, ...WOODEN_BUILDING_TYPE_LABELS]) {
    const t = v.trim();
    if (!t || seen.has(t)) continue;
    seen.add(t);
    out.push(t);
  }
  return out;
}

export function isWoodenBuildingType(value: string | null | undefined): boolean {
  const v = (value || "").trim();
  if (!v) return false;
  if (v === "Деревянный") return true;
  return WOODEN_LABEL_SET.has(v);
}

export function getWoodenHouseConfig(
  id: string | null | undefined,
): WoodenHouseConfig | undefined {
  if (!id) return undefined;
  return WOODEN_HOUSE_CONFIGS.find((c) => c.id === id);
}

export function getWoodenHouseConfigByBuildingType(
  label: string | null | undefined,
): WoodenHouseConfig | undefined {
  const v = (label || "").trim();
  if (!v) return undefined;
  return WOODEN_HOUSE_CONFIGS.find((c) => c.buildingType === v);
}

export function woodenConfigsByGroup(group: WoodenHouseGroup): WoodenHouseConfig[] {
  return WOODEN_HOUSE_CONFIGS.filter((c) => c.group === group);
}

export function matchesBuildingTypeFilter(
  actual: string,
  selected: string[],
): boolean {
  if (!selected.length) return true;
  if (selected.includes(actual)) return true;
  if (selected.includes("Деревянный") && isWoodenBuildingType(actual)) {
    return true;
  }
  return false;
}
